/**
 * Universal AppIcon React Component
 */
export default function AppIcon({
  name,
  size = 20,
  color,
  strokeWidth = 2.2,
  className = "",
  style = {},
  ...props
}) {
  let key = "helpcircle";
  if (name && EMOJI_TO_ICON[name]) {
    key = EMOJI_TO_ICON[name];
  } else if (name) {
    key = String(name).toLowerCase().replace(/[-_\s]/g, "");
  }

  const IconComp = ICON_COMPONENTS[key] || HelpCircle;

  return React.createElement(IconComp, {
    size,
    color,
    strokeWidth,
    className: `app-icon ${className}`,
    style: { display: "inline-block", verticalAlign: "middle", ...style },
    ...props
  });
}
